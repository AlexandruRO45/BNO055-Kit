#!/usr/bin/env python3
"""compare_session.py — sync + side-by-side compare a BNO session vs a CAN capture.

The capture is any candump -L log carrying the IMU frames; it need not come
from a VISAN airframe — point it at any host's capture and it works.

The two sensors sit in different body frames, so the SAME samples are written
under a per-preset subfolder. Pick one preset (default ``raw``) or pass
``--preset`` more than once to emit both side by side:

    raw            as-reported: each sensor's literal output, no transform.
    frame-aligned  both brought into one common body frame: BNO lin_acc gets
                   the quaternion-rotated gravity restored
                   (lin_acc - R(q)@[0,0,g]) and the gyro mount
                   diag(1,-1,-1) is applied, so the delta is the true
                   sensor-agreement residual rather than a frame artifact.

Each run writes, under <out-dir>/<preset>/:

    compare.jsonl        one row per sample: t + {signal: {bno, can, delta}}
    compare_summary.json per-signal stats + the conventions/offsets used

plus, once at <out-dir>/: sync.json (clock offset + jitter) and a README.md
that documents the conventions and the exact commands that produced the tree.

Usage:
    compare_session.py <bno_session_dir> <capture_dir>
                       [--out-dir DIR] [--preset raw] [--preset frame-aligned]
                       [--euler-convention none|ned_to_nwu]
                       [--accel-convention raw|reconstruct_gravity]
                       [--gyro-convention none|negate|rot_x180]
                       [--method auto|correlation|anchor] [--fs 20] [--max-lag 5]
                       [--window LO:HI]  # seconds, relative to overlap start

Exit codes: 0 ok, 1 analysis failed, 2 bad arguments.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

# Re-exec under the app venv when launched with any other interpreter.
_APP_VENV = Path("/opt/bno055/.venv")
if (_APP_VENV / "bin/python").is_file() \
        and Path(sys.prefix).resolve() != _APP_VENV.resolve():
    os.execv(str(_APP_VENV / "bin/python"),
             [str(_APP_VENV / "bin/python"), *sys.argv])

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from bno055_kit.analysis.compare import (  # noqa: E402
    compare as compare_signals,
)
from bno055_kit.analysis.compare import (  # noqa: E402  # noqa: E402
    load_can_signals,
    load_imu_signals,
)
from bno055_kit.analysis.sync import (  # noqa: E402
    align,
    load_can_series,
    load_imu_session,
)

# Each preset is a named bundle of the three conventions. A preset is just a
# starting point: the matching --*-convention flag overrides that axis.
PRESETS: dict[str, dict[str, str]] = {
    "raw": {"euler": "none", "accel": "raw", "gyro": "none"},
    "frame-aligned": {"euler": "none", "accel": "reconstruct_gravity",
                      "gyro": "rot_x180"},
}

PRESET_HELP = {
    "raw": "as-reported: each sensor's literal output, no transform",
    "frame-aligned": "common body frame: gravity restored via R(q), "
                     "gyro mount diag(1,-1,-1) applied",
}


def _write_readme(out_dir: Path, presets: list[str], sync_res, args) -> None:
    preset_rows = "\n".join(
        f"| `{p}` | {PRESET_HELP[p]} | euler={PRESETS[p]['euler']}, "
        f"accel={PRESETS[p]['accel']}, gyro={PRESETS[p]['gyro']} |"
        for p in presets)
    preset_flags = " ".join(f"--preset {p}" for p in presets)
    cmd = (f"python3 scripts/analysis/compare_session.py "
           f"{args.bno_dir} {args.capture_dir} "
           f"--out-dir {out_dir} {preset_flags}")
    text = f"""# Analysis bundle — {out_dir.name}

Generated by `scripts/analysis/compare_session.py`. This directory holds one
subfolder per **preset** (a named set of conventions). Each preset rewrites the
SAME aligned samples under a different view of the two sensors' frames.

## Files
- `sync.json` (here, shared) — clock offset + jitter between the BNO monotonic
  timeline and the CAN wall-clock timeline. `offset_s` is added to IMU time to
  reach CAN time.
- `<preset>/compare.jsonl` — one line per sample: `{{"t": ..., "signals":
  {{"signal": {{"bno": ..., "can": ..., "delta": ...}}}}}}`, iterating the
  timeline (not the signals).
- `<preset>/compare_summary.json` — per-signal stats + the conventions + offset
  used for that view.

## Presets (the conventions)
| preset | what it means | conventions |
|---|---|---|
{preset_rows}

`raw` is the honest side-by-side of what each sensor literally reported; the
large deltas there are the *frame* difference (BNO gravity-stripped lin_acc vs
CAN gravity-included accel; the gyro mount rotation). `frame-aligned` removes
those known frame differences so the delta is the true sensor-agreement
residual.

## Regenerate
```bash
{cmd}
```
Pass `--preset` once for one view, or once per view to emit both side by side.
The per-axis overrides (`--euler-convention`, `--accel-convention`,
`--gyro-convention`) replace a single convention without changing the others.
"""
    (out_dir / "README.md").write_text(text, encoding="utf-8")


def _parse_presets(values: list[str]) -> list[str]:
    out: list[str] = []
    for v in values:
        for name in v.split(","):
            name = name.strip()
            if not name:
                continue
            if name not in PRESETS:
                raise ValueError(f"unknown preset {name!r}; "
                                 f"choose one of {sorted(PRESETS)}")
            if name not in out:
                out.append(name)
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="compare_session",
                                description=__doc__.splitlines()[0])
    p.add_argument("bno_dir", help="BNO055 session dir (session.json + imu.jsonl)")
    p.add_argument("capture_dir", help="CAN capture session dir (holds can.candump)")
    p.add_argument("--out-dir", default=None,
                   help="bundle root (default <capture_dir>/analysis); each "
                        "selected preset is written to <out-dir>/<preset>/")
    p.add_argument("--candump", default=None,
                   help="candump log (default <capture_dir>/can.candump)")
    p.add_argument("--preset", action="append", metavar="NAME",
                   help=f"preset to emit; repeat or comma-separate for several "
                        f"(default raw). One of: {', '.join(PRESETS)}")
    p.add_argument("--method", choices=("auto", "correlation", "anchor"), default="auto")
    p.add_argument("--fs", type=float, default=20.0)
    p.add_argument("--max-lag", type=float, default=5.0)
    p.add_argument("--euler-convention", choices=("none", "ned_to_nwu"), default=None,
                   help="override the preset's euler convention")
    p.add_argument("--accel-convention", choices=("raw", "reconstruct_gravity"),
                   default=None, help="override the preset's accel convention")
    p.add_argument("--gyro-convention", choices=("none", "negate", "rot_x180"),
                   default=None, help="override the preset's gyro convention")
    p.add_argument("--window", default=None,
                   help="compare only this time window, LO:HI seconds from overlap start")
    args = p.parse_args(argv)

    bno_dir = Path(args.bno_dir)
    capture_dir = Path(args.capture_dir)
    if not bno_dir.is_dir():
        print(f"[FAIL] not a directory: {bno_dir}", file=sys.stderr)
        return 2
    candump = Path(args.candump) if args.candump else capture_dir / "can.candump"
    if not candump.is_file():
        print(f"[FAIL] not a file: {candump}", file=sys.stderr)
        return 2
    try:
        presets = _parse_presets(args.preset or ["raw"])
    except ValueError as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 2

    out_dir = Path(args.out_dir) if args.out_dir else capture_dir / "analysis"
    out_dir.mkdir(parents=True, exist_ok=True)

    window = None
    if args.window:
        try:
            lo, hi = (float(x) for x in args.window.split(":"))
        except ValueError:
            print("[FAIL] --window must be LO:HI seconds", file=sys.stderr)
            return 2
        window = (lo, hi)

    # 1. sync (shared across presets) -------------------------------------
    try:
        imu_sync = load_imu_session(bno_dir)
        can_sync = load_can_series(candump)
        sync_res = align(imu_sync, can_sync, method=args.method,
                         fs=args.fs, max_lag_s=args.max_lag)
    except ValueError as exc:
        print(f"[FAIL] sync: {exc}", file=sys.stderr)
        return 1

    sync_manifest = {
        "schema_version": 1,
        "imu_session": str(bno_dir),
        "imu_session_id": imu_sync.session_id,
        "candump_log": str(candump),
        "can_frames": can_sync.n_frames,
        **sync_res.to_dict(),
    }
    (out_dir / "sync.json").write_text(
        json.dumps(sync_manifest, indent=2) + "\n", encoding="utf-8")

    # 2. compare — one subfolder per preset -------------------------------
    imu = load_imu_signals(bno_dir)
    can = load_can_signals(candump)
    results: dict[str, tuple] = {}
    for preset in presets:
        conv = dict(PRESETS[preset])
        conv["euler"] = args.euler_convention or conv["euler"]
        conv["accel"] = args.accel_convention or conv["accel"]
        conv["gyro"] = args.gyro_convention or conv["gyro"]
        try:
            result, rows = compare_signals(
                imu, can, sync_res.offset_s,
                method=sync_res.method, confidence=sync_res.confidence,
                euler_convention=conv["euler"], accel_convention=conv["accel"],
                gyro_convention=conv["gyro"], window_s=window)
        except ValueError as exc:
            print(f"[FAIL] compare ({preset}): {exc}", file=sys.stderr)
            return 1
        sub = out_dir / preset
        sub.mkdir(parents=True, exist_ok=True)
        with open(sub / "compare.jsonl", "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r) + "\n")
        summary = result.to_summary_dict()
        summary["preset"] = preset
        summary["imu_session"] = str(bno_dir)
        summary["capture_session"] = str(capture_dir)
        summary["candump_log"] = str(candump)
        summary["can_frames"] = can.n_frames
        summary["imu_n_bad_lines"] = imu.n_bad_lines
        (sub / "compare_summary.json").write_text(
            json.dumps(summary, indent=2) + "\n", encoding="utf-8")
        results[preset] = (result, len(rows))

    _write_readme(out_dir, presets, sync_res, args)

    # 3. report -------------------------------------------------------------
    print(f"[OK] {out_dir}")
    print(f"     sync      : {sync_res.method} ({sync_res.confidence}), "
          f"offset {sync_res.offset_s * 1e3:+.3f} ms")
    for preset in presets:
        result, n_rows = results[preset]
        print(f"     [{preset}] {n_rows:,} rows -> {out_dir / preset}/")
        print(f"        conventions: {result.conventions}")
        for s in result.summaries:
            print(f"          {s.bno_key:<9} vs {s.can_signal:<14} "
                  f"rmse={s.rmse:8.4f} max|d|={s.max_abs_delta:8.4f} "
                  f"mean={s.mean_delta:+8.4f} {s.unit}  n={s.n:,}")
        for note in result.notes:
            print(f"          note: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
